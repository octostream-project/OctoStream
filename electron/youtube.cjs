// Extractor de YouTube para desktop — equivalente a NewPipeExtractor en
// Android. Lanza el binario yt-dlp empaquetado (extraResources) y da la
// misma superficie que el plugin Capacitor Youtube: resolve/search/
// searchMore/suggest/getChannel/getChannelInfo.
const { spawn } = require('child_process')
const https = require('https')

let ytdlpResolver = null
let proxyAgentFor = null // (host) => agent | undefined — lo inyecta main.cjs
let warpProxyUrl = null  // socks5://127.0.0.1:1819 cuando WARP está activo

function init({ resolver, agentFor, getWarpProxyUrl }) {
  ytdlpResolver = resolver
  proxyAgentFor = agentFor
  warpProxyUrl = getWarpProxyUrl
}

function ytdlpPath() {
  const exe = ytdlpResolver()
  if (!exe) throw new Error('yt-dlp no encontrado (build/ytdlp o resources)')
  return exe
}

function runYtDlp(args, timeoutMs = 90000) {
  return new Promise((resolve, reject) => {
    // Cuando WARP está activo, yt-dlp sale por el túnel (igual que el
    // downloader OkHttp del plugin Android); socks5h = DNS remoto.
    const finalArgs = warpProxyUrl && warpProxyUrl()
      ? ['--proxy', warpProxyUrl(), ...args]
      : args
    const proc = spawn(ytdlpPath(), finalArgs, { stdio: ['ignore', 'pipe', 'pipe'] })
    let out = ''
    let err = ''
    const timer = setTimeout(() => {
      try { proc.kill('SIGKILL') } catch { /* ya muerto */ }
      reject(new Error(`yt-dlp timeout (${timeoutMs / 1000}s)`))
    }, timeoutMs)
    proc.stdout.on('data', c => { out += c.toString(); if (out.length > 24e6) proc.kill('SIGKILL') })
    proc.stderr.on('data', c => { err += c.toString(); if (err.length > 8192) err = err.slice(-8192) })
    proc.on('error', (e) => { clearTimeout(timer); reject(e) })
    proc.on('exit', (code) => {
      clearTimeout(timer)
      if (code === 0) resolve(out)
      else reject(new Error(err.trim().split('\n').slice(-3).join(' ') || `yt-dlp exit ${code}`))
    })
  })
}

async function runJson(args, timeoutMs) {
  const out = await runYtDlp(args, timeoutMs)
  return JSON.parse(out)
}

// ─── Mapeo a las definiciones del plugin ────────────────────────────────────

function bestThumb(thumbnails, videoId) {
  const t = (thumbnails || []).filter(x => x?.url).sort((a, b) => (b.width || 0) - (a.width || 0))[0]
  return t?.url || (videoId ? `https://i.ytimg.com/vi/${videoId}/hqdefault.jpg` : '')
}

function mapItem(e) {
  if (!e) return null
  const id = e.id || (e.url || '').match(/v=([a-zA-Z0-9_-]+)/)?.[1] || ''
  return {
    name: e.title || '',
    url: id ? `https://www.youtube.com/watch?v=${id}` : (e.url || ''),
    uploader: e.channel || e.uploader || '',
    uploaderUrl: e.channel_url || e.uploader_url || '',
    uploaderAvatarUrl: '',
    duration: e.duration || 0,
    views: e.view_count || 0,
    thumbnailUrl: bestThumb(e.thumbnails, id),
    isLive: e.live_status === 'is_live',
  }
}

async function resolve({ url }) {
  const d = await runJson(['-j', '--no-playlist', '--no-warnings', url], 90000)
  // Progresivos (audio+vídeo juntos) — el <video>/mpv los reproducen directo.
  const streams = (d.formats || [])
    .filter(f => f.url && f.vcodec && f.vcodec !== 'none' && f.acodec && f.acodec !== 'none' && /^https?$/.test(f.protocol || ''))
    .sort((a, b) => (b.height || 0) - (a.height || 0))
    .map(f => ({
      url: f.url,
      mimeType: f.ext === 'mp4' ? 'video/mp4' : `video/${f.ext || 'mp4'}`,
      quality: f.format_note || (f.height ? `${f.height}p` : ''),
      format: 'mp4',
    }))
  // Manifest HLS: en directos es el único camino; en VOD sin progresivos da
  // adaptativo vía hls.js (equivalente al dashUrl que usa el plugin Android).
  const m3u8 = (d.formats || []).find(f => f.url && /m3u8/.test(f.protocol || ''))
  const hlsUrl = (d.is_live || streams.length === 0) ? (m3u8?.url || d.url || '') : ''
  const subtitles = []
  for (const [lang, tracks] of Object.entries(d.subtitles || {})) {
    const vtt = (tracks || []).find(t => t.ext === 'vtt' && t.url) || (tracks || []).find(t => t.url)
    if (vtt) subtitles.push({ url: vtt.url, language: lang, name: lang.toUpperCase(), autoGenerated: false, mimeType: `text/${vtt.ext}` })
  }
  for (const [lang, tracks] of Object.entries(d.automatic_captions || {})) {
    const vtt = (tracks || []).find(t => t.ext === 'vtt' && t.url)
    if (vtt) subtitles.push({ url: vtt.url, language: lang, name: `${lang.toUpperCase()} (auto)`, autoGenerated: true, mimeType: 'text/vtt' })
  }
  return { title: d.title || '', streams, hlsUrl, subtitles }
}

const PAGE_SIZE = 20

async function search({ query }) {
  const d = await runJson([`ytsearch${PAGE_SIZE}:${query}`, '--flat-playlist', '-J', '--no-warnings'], 60000)
  const items = (d.entries || []).map(mapItem).filter(Boolean)
  return { items, hasNextPage: items.length >= PAGE_SIZE, nextPage: { offset: items.length } }
}

async function searchMore({ query, nextPage }) {
  const start = (nextPage?.offset || 0) + 1
  const end = start + PAGE_SIZE - 1
  // ytsearchN: debe pedir al menos `end` resultados para que el slice exista.
  const d = await runJson([`ytsearch${end}:${query}`, '--flat-playlist', '-J', '--no-warnings', '--playlist-start', String(start), '--playlist-end', String(end)], 60000)
  const items = (d.entries || []).map(mapItem).filter(Boolean)
  return { items, hasNextPage: items.length >= PAGE_SIZE, nextPage: { offset: start + items.length - 1 } }
}

// Sugerencias: endpoint público de YouTube (el que usa la web). Respeta el
// agente de WARP/bypass del proxy local igual que el downloader Android.
async function suggest({ query }) {
  const target = `https://suggestqueries.google.com/complete/search?client=firefox&ds=yt&q=${encodeURIComponent(query)}`
  return new Promise((resolve, reject) => {
    const agent = proxyAgentFor ? proxyAgentFor('suggestqueries.google.com') : undefined
    const req = https.get(target, { agent, timeout: 15000 }, (res) => {
      let body = ''
      res.on('data', c => { body += c })
      res.on('end', () => {
        try {
          const parsed = JSON.parse(body)
          resolve({ suggestions: Array.isArray(parsed?.[1]) ? parsed[1] : [] })
        } catch (e) { reject(e) }
      })
    })
    req.on('timeout', () => req.destroy(new Error('suggest timeout')))
    req.on('error', reject)
  })
}

async function getChannel({ url }) {
  let chUrl = url || ''
  if (!/\/(videos|streams|shorts)\b/.test(chUrl)) chUrl = chUrl.replace(/\/+$/, '') + '/videos'
  const d = await runJson([chUrl, '--flat-playlist', '-J', '--no-warnings', '--playlist-end', '30'], 90000)
  const items = (d.entries || []).map(mapItem).filter(Boolean)
  return {
    name: d.channel || d.uploader || '',
    url: d.channel_url || d.uploader_url || chUrl,
    description: d.description || '',
    subscriberCount: d.channel_follower_count || 0,
    avatarUrl: bestThumb(d.thumbnails, ''),
    bannerUrl: '',
    items,
  }
}

async function getChannelInfo({ url }) {
  let chUrl = url || ''
  if (!/\/(videos|streams|shorts)\b/.test(chUrl)) chUrl = chUrl.replace(/\/+$/, '') + '/videos'
  const d = await runJson([chUrl, '--flat-playlist', '-J', '--no-warnings', '--playlist-end', '1'], 60000)
  return {
    name: d.channel || d.uploader || '',
    url: d.channel_url || d.uploader_url || chUrl,
    subscriberCount: d.channel_follower_count || 0,
    avatarUrl: bestThumb(d.thumbnails, ''),
  }
}

module.exports = { init, resolve, search, searchMore, suggest, getChannel, getChannelInfo }
